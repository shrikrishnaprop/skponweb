"""Refresh xi38 font assets and picker metadata from the template font folder.

After replacing .woff2 files in xnglo-fontpicker-template/components/hsciifp/
fonts/hscii/xi38font, run `python scripts/update_xi38_fonts.py` from any
project in C:\\skpweb. It copies the font set and regenerates each project's
varfonts.ts and font-catalog.js.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import sys
from pathlib import Path


FONT_RELATIVE_PATH = Path("components/hsciifp/fonts/hscii/xi38font")
TEMPLATE_NAME = "xnglo-fontpicker-template"


def safe_identifier(stem: str) -> str:
    value = re.sub(r"[^A-Za-z0-9_$]", "_", stem)
    return f"font_{value}" if not value or value[0].isdigit() else value


def get_fonts(folder: Path) -> list[Path]:
    fonts = sorted(
        (p for p in folder.iterdir() if p.is_file() and p.suffix.lower() == ".woff2"),
        key=lambda p: p.name.casefold(),
    )
    if not fonts:
        raise ValueError(f"No .woff2 files found in {folder}")
    ids = [safe_identifier(p.stem).casefold() for p in fonts]
    if len(ids) != len(set(ids)):
        raise ValueError("Font filenames must produce unique JavaScript identifiers.")
    return fonts


def varfonts_source(fonts: list[Path]) -> str:
    definitions = []
    refs = []
    for font in fonts:
        name = safe_identifier(font.stem)
        definitions.append(
            f"const {name} = localFont({{\n"
            f'  src: "./fonts/hscii/xi38font/{font.name}",\n'
            f'  variable: "--font-{name}",\n'
            '  display: "swap",\n'
            "});"
        )
        refs.append(f"  {name},")
    return (
        "// Generated by scripts/update_xi38_fonts.py.\n"
        'import localFont from "next/font/local";\n\n'
        + "\n\n".join(definitions)
        + "\n\nexport const localFontVariables = [\n"
        + "\n".join(refs)
        + "\n];\n"
    )


def catalog_source(fonts: list[Path]) -> str:
    entries = [
        {
            "id": safe_identifier(font.stem),
            "name": font.stem,
            "variable": f"var(--font-{safe_identifier(font.stem)})",
        }
        for font in fonts
    ]
    default_id = next((e["id"] for e in entries if e["id"].casefold() == "xh38asc"), entries[0]["id"])
    return (
        "// Generated by scripts/update_xi38_fonts.py.\n"
        f"export const LOCAL_FONTS = {json.dumps(entries, ensure_ascii=False, indent=2)};\n"
        f"export const DEFAULT_FONT_ID = {json.dumps(default_id)};\n"
    )


def picker_source() -> str:
    return '''"use client";

import { useEffect, useState } from "react";
import { DEFAULT_FONT_ID, LOCAL_FONTS } from "./font-catalog";

const STORAGE_KEY = "user-local-font";

function applyGlobalFont(fontId: string) {
  const font = LOCAL_FONTS.find((item) => item.id === fontId);
  if (!font) return;

  document.documentElement.style.setProperty("--current-active-font", font.variable);
  document.body.style.fontFamily = font.variable;
}

export default function LocalFontPicker() {
  const [selectedFont, setSelectedFont] = useState(DEFAULT_FONT_ID);

  useEffect(() => {
    const savedFont = localStorage.getItem(STORAGE_KEY);
    const fontId = LOCAL_FONTS.some((font) => font.id === savedFont)
      ? savedFont!
      : DEFAULT_FONT_ID;

    setSelectedFont(fontId);
    applyGlobalFont(fontId);
  }, []);

  function handleFontChange(fontId: string) {
    setSelectedFont(fontId);
    localStorage.setItem(STORAGE_KEY, fontId);
    applyGlobalFont(fontId);
  }

  return (
    <label style={{ display: "flex", alignItems: "center", gap: 6, fontSize: 11, fontWeight: 700, whiteSpace: "nowrap" }}>
      <span>Font</span>
      <select
        aria-label="Choose display font"
        value={selectedFont}
        onChange={(event) => handleFontChange(event.target.value)}
        style={{ maxWidth: 160, padding: "8px 9px", border: "1px solid currentColor", borderRadius: 4, background: "white", color: "#26313d", font: "inherit" }}
      >
        {LOCAL_FONTS.map((font) => (
          <option key={font.id} value={font.id}>
            {font.name}
          </option>
        ))}
      </select>
    </label>
  );
}
'''


def update_layout(project: Path) -> None:
    app_dir = project / "app"
    layout = next((p for p in (app_dir / "layout.tsx", app_dir / "layout.js") if p.is_file()), None)
    if not layout:
        return

    text = layout.read_text(encoding="utf-8")
    import_pattern = r'import\s*\{[\s\S]*?\}\s*from\s*["\']@/components/hsciifp/varfonts["\'];'
    import_statement = 'import { localFontVariables } from "@/components/hsciifp/varfonts";'
    if re.search(import_pattern, text):
        text = re.sub(import_pattern, import_statement, text, count=1)
    elif 'from "@/components/hsciifp/varfonts"' not in text:
        text = import_statement + "\n" + text

    text, changed = re.subn(
        r"className=\{`[^`]*`\}",
        'className={localFontVariables.map((font) => font.variable).join(" ")}',
        text,
        count=1,
    )
    if changed == 0 and "localFontVariables.map((font) => font.variable)" not in text:
        raise RuntimeError(f"Could not update font class list in {layout}; please review it manually.")

    layout.write_text(text, encoding="utf-8")


def ensure_usage_notes(template_root: Path) -> None:
    readme = template_root / "readme.md"
    if not readme.is_file():
        return
    text = readme.read_text(encoding="utf-8")
    if "python scripts/update_xi38_fonts.py" in text:
        return
    text += (
        "\n\n## Refresh the xi38 fonts\n\n"
        "Replace the `.woff2` files in `components/hsciifp/fonts/hscii/xi38font/`, "
        "then run `python scripts/update_xi38_fonts.py`. The script refreshes "
        "`varfonts.ts`, the picker catalogue and component, and matching projects "
        "under `C:\\skpweb`. Restart the dev server or rebuild afterward.\n"
    )
    readme.write_text(text, encoding="utf-8")


def sync_project(project: Path, source_folder: Path, fonts: list[Path]) -> None:
    dest_folder = project / FONT_RELATIVE_PATH
    dest_folder.mkdir(parents=True, exist_ok=True)
    keep = {p.name.casefold() for p in fonts}

    for old in dest_folder.iterdir():
        if old.is_file() and old.suffix.lower() == ".woff2" and old.name.casefold() not in keep:
            old.unlink()
    for font in fonts:
        target = dest_folder / font.name
        if font.resolve() != target.resolve():
            shutil.copy2(font, target)

    component_dir = project / "components/hsciifp"
    component_dir.mkdir(parents=True, exist_ok=True)
    (component_dir / "varfonts.ts").write_text(varfonts_source(fonts), encoding="utf-8")
    (component_dir / "font-catalog.js").write_text(catalog_source(fonts), encoding="utf-8")
    (component_dir / "LocalFontPicker.tsx").write_text(picker_source(), encoding="utf-8")
    update_layout(project)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--template-root", type=Path, help="Font source project (defaults to sibling xnglo-fontpicker-template)")
    parser.add_argument("--projects-root", type=Path, help="Folder containing the Next.js projects")
    parser.add_argument("--project", type=Path, action="append", help="Update only this project; can be repeated")
    args = parser.parse_args()

    current_project = Path(__file__).resolve().parents[1]
    template_root = (args.template_root or Path(os.environ.get(
        "XNGLO_TEMPLATE_ROOT", str(current_project.parent / TEMPLATE_NAME)
    ))).resolve()
    projects_root = (args.projects_root or Path(os.environ.get(
        "SKPWEB_PROJECTS_ROOT", str(template_root.parent)
    ))).resolve()
    source_folder = template_root / FONT_RELATIVE_PATH

    if not source_folder.is_dir():
        print(f"Font source folder does not exist: {source_folder}", file=sys.stderr)
        return 1

    fonts = get_fonts(source_folder)
    projects = [p.resolve() for p in args.project] if args.project else [
        child.resolve()
        for child in projects_root.iterdir()
        if child.is_dir() and (child / FONT_RELATIVE_PATH).is_dir()
    ]
    if not args.project and template_root not in projects:
        projects.append(template_root)

    for project in sorted(set(projects), key=lambda p: str(p).casefold()):
        sync_project(project, source_folder, fonts)
        print(f"Updated {project}: {len(fonts)} fonts")

    if not args.project:
        script_copy = template_root / "scripts/update_xi38_fonts.py"
        script_copy.parent.mkdir(parents=True, exist_ok=True)
        if script_copy.resolve() != Path(__file__).resolve():
            shutil.copy2(Path(__file__).resolve(), script_copy)
        ensure_usage_notes(template_root)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
