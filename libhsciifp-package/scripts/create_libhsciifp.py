"""Generate the standalone libhsciifp React package from xi38 .woff2 files."""

from __future__ import annotations

import argparse
import json
import re
import shutil
from pathlib import Path


DEFAULT_SOURCE = Path(r"C:\xpzs\pff\xnglofonts\woff2\xi38woff2\xi38asc")
LICENSE_DIR = Path(__file__).resolve().parent / "libhsciifp-license"


def safe_identifier(stem: str) -> str:
    value = re.sub(r"[^A-Za-z0-9_$]", "_", stem)
    return f"font_{value}" if not value or value[0].isdigit() else value


def scan_fonts(source: Path) -> list[Path]:
    fonts = sorted(
        (item for item in source.iterdir() if item.is_file() and item.suffix.lower() == ".woff2"),
        key=lambda item: item.name.casefold(),
    )
    if not fonts:
        raise ValueError(f"No .woff2 files found in {source}")
    ids = [safe_identifier(item.stem).casefold() for item in fonts]
    if len(ids) != len(set(ids)):
        raise ValueError("Font filenames must produce unique identifiers")
    return fonts


def write_package(source: Path, output: Path) -> None:
    fonts = scan_fonts(source)
    output.mkdir(parents=True, exist_ok=True)
    asset_dir = output / "fonts"
    asset_dir.mkdir(exist_ok=True)
    keep = {font.name.casefold() for font in fonts}
    for old in asset_dir.glob("*.woff2"):
        if old.name.casefold() not in keep:
            old.unlink()
    for font in fonts:
        shutil.copy2(font, asset_dir / font.name)

    catalog = [
        {"id": safe_identifier(font.stem), "name": font.stem, "family": f"xi38asc-{font.stem}"}
        for font in fonts
    ]
    default_id = next((font["id"] for font in catalog if font["id"].casefold() == "xh38asc"), catalog[0]["id"])
    (output / "font-catalog.json").write_text(
        json.dumps({"fonts": catalog, "defaultFontId": default_id}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )

    css = ["/* Generated by scripts/create_libhsciifp.py. */"]
    for font in fonts:
        family = f"xi38asc-{font.stem}"
        css.extend([
            "@font-face {",
            f'  font-family: "{family}";',
            f'  src: url("./fonts/{font.name}") format("woff2");',
            "  font-style: normal;",
            "  font-weight: 400;",
            "  font-display: swap;",
            "}",
            "",
        ])
    (output / "fonts.css").write_text("\n".join(css).rstrip() + "\n", encoding="utf-8")

    (output / "index.js").write_text('''"use client";
"use strict";

const React = require("react");
const catalog = require("./font-catalog.json");

const FONT_CATALOG = catalog.fonts;
const DEFAULT_FONT_ID = catalog.defaultFontId;
const DEFAULT_STORAGE_KEY = "user-local-font";

function applyFont(fontId) {
  if (typeof document === "undefined") return;
  const font = FONT_CATALOG.find((item) => item.id === fontId);
  if (!font) return;
  const family = `"${font.family}", sans-serif`;
  document.documentElement.style.setProperty("--current-active-font", family);
  document.body.style.fontFamily = family;
}

function FontPicker(props) {
  const options = props || {};
  const storageKey = options.storageKey || DEFAULT_STORAGE_KEY;
  const requestedDefault = options.defaultFontId;
  const baseDefault = FONT_CATALOG.some((font) => font.id === requestedDefault) ? requestedDefault : DEFAULT_FONT_ID;
  const [selectedFont, setSelectedFont] = React.useState(baseDefault);

  React.useEffect(() => {
    let saved;
    try { saved = window.localStorage.getItem(storageKey); } catch (_) { /* Storage may be blocked. */ }
    const next = FONT_CATALOG.some((font) => font.id === saved) ? saved : baseDefault;
    setSelectedFont(next);
    applyFont(next);
  }, [storageKey, baseDefault]);

  function handleChange(event) {
    const fontId = event.target.value;
    setSelectedFont(fontId);
    applyFont(fontId);
    try { window.localStorage.setItem(storageKey, fontId); } catch (_) { /* Storage may be blocked. */ }
    if (typeof options.onChange === "function") options.onChange(fontId);
  }

  return React.createElement("label", { className: options.className, style: options.style },
    React.createElement("span", null, options.label || "Font"),
    React.createElement("select", {
      "aria-label": options.ariaLabel || "Choose display font",
      value: selectedFont,
      onChange: handleChange,
    }, FONT_CATALOG.map((font) => React.createElement("option", { key: font.id, value: font.id }, font.name))));
}

module.exports = {
  FontPicker,
  LocalFontPicker: FontPicker,
  Hsciifontpicker: FontPicker,
  FONT_CATALOG,
  DEFAULT_FONT_ID,
  applyFont,
  default: FontPicker,
};
''', encoding="utf-8")

    (output / "index.d.ts").write_text('''import * as React from "react";

export interface FontPickerProps {
  defaultFontId?: string;
  storageKey?: string;
  label?: string;
  ariaLabel?: string;
  className?: string;
  style?: React.CSSProperties;
  onChange?: (fontId: string) => void;
}

export interface FontDefinition { id: string; name: string; family: string; }
export const FONT_CATALOG: readonly FontDefinition[];
export const DEFAULT_FONT_ID: string;
export function applyFont(fontId: string): void;
export const FontPicker: React.ComponentType<FontPickerProps>;
export const LocalFontPicker: typeof FontPicker;
export const Hsciifontpicker: typeof FontPicker;
export default FontPicker;
''', encoding="utf-8")

    package = {
        "name": "libhsciifp",
        "version": "1.0.0",
        "description": "React font picker and xi38asc web fonts",
        "main": "./index.js",
        "types": "./index.d.ts",
        "files": ["index.js", "index.d.ts", "font-catalog.json", "fonts.css", "fonts/", "README.md", "LICENSE", "LICENSE.md"],
        "exports": {
            ".": { "types": "./index.d.ts", "require": "./index.js", "default": "./index.js" },
            "./fonts.css": "./fonts.css",
            "./fonts/*": "./fonts/*",
            "./package.json": "./package.json",
        },
        "peerDependencies": {"react": ">=18"},
        "sideEffects": ["./fonts.css"],
        "license": "SEE LICENSE IN LICENSE.md",
        "engines": {"node": ">=18"},
    }
    (output / "package.json").write_text(json.dumps(package, indent=2) + "\n", encoding="utf-8")
